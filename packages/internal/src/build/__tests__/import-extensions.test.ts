import path from 'node:path'

import { describe, expect, it } from 'vitest'

import { applyImportExtensions } from '../import-extensions.js'

// Pretend the importer lives at api/src/functions/graphql.ts so that
// relative imports like `../lib/db` resolve to the fixture files.
const FIXTURE_SRC = path.join(__dirname, '__fixtures__/import-extensions/src')
const IMPORTER = path.join(FIXTURE_SRC, 'functions/graphql.ts')

describe('applyImportExtensions', () => {
  it('appends .js when a .ts source file exists', () => {
    const code = `import { db } from '../lib/db'`
    expect(applyImportExtensions(code, IMPORTER)).toBe(
      `import { db } from '../lib/db.js'`,
    )
  })

  it('appends .js when a .jsx source file exists (esbuild outputs .js)', () => {
    // Although server.jsx exists in source, esbuild with loader:'js' compiles
    // it to server.js, so imports must use the .js extension at runtime.
    const code = `import { Server } from '../lib/server'`
    expect(applyImportExtensions(code, IMPORTER)).toBe(
      `import { Server } from '../lib/server.js'`,
    )
  })

  it('handles double-quoted imports', () => {
    const code = `import { db } from "../lib/db"`
    expect(applyImportExtensions(code, IMPORTER)).toBe(
      `import { db } from "../lib/db.js"`,
    )
  })

  it('handles re-exports', () => {
    const code = `export { db } from '../lib/db'`
    expect(applyImportExtensions(code, IMPORTER)).toBe(
      `export { db } from '../lib/db.js'`,
    )
  })

  it('leaves imports that already have the correct .js extension alone', () => {
    const code = `import { x } from '../lib/already.js'`
    // already.js exists on disk, so the .js extension is already correct
    expect(applyImportExtensions(code, IMPORTER)).toBe(code)
  })

  it('normalises a .js extension that points at a .ts source file', () => {
    // Caller wrote ./db.js but the source is db.ts — strip and re-add.
    const code = `import { db } from '../lib/db.js'`
    expect(applyImportExtensions(code, IMPORTER)).toBe(
      `import { db } from '../lib/db.js'`,
    )
  })

  it('appends .js when only a .js source file exists (no .ts)', () => {
    const code = `import { x } from '../lib/already'`
    // already.js exists, so it should get .js appended
    expect(applyImportExtensions(code, IMPORTER)).toBe(
      `import { x } from '../lib/already.js'`,
    )
  })

  it('leaves imports where no matching file exists unchanged', () => {
    const code = `import { x } from '../lib/nonexistent'`
    expect(applyImportExtensions(code, IMPORTER)).toBe(code)
  })

  it('leaves bare package specifiers untouched', () => {
    const code = `import { foo } from 'some-package'`
    expect(applyImportExtensions(code, IMPORTER)).toBe(code)
  })

  it('handles dynamic imports', () => {
    const code = `const mod = await import('../lib/db')`
    expect(applyImportExtensions(code, IMPORTER)).toBe(
      `const mod = await import('../lib/db.js')`,
    )
  })

  it('handles dynamic imports with double quotes', () => {
    const code = `const mod = await import("../lib/db")`
    expect(applyImportExtensions(code, IMPORTER)).toBe(
      `const mod = await import("../lib/db.js")`,
    )
  })

  it('appends .js for SDL files whose source is a .ts with compound extension', () => {
    // contacts.sdl.ts compiles to contacts.sdl.js; the import specifier
    // generated by applyImportDir is `../graphql/contacts.sdl` (no .js).
    // applyImportExtensions must probe for contacts.sdl.ts and append .js.
    const code = `import contactsSdl from '../graphql/contacts.sdl'`
    expect(applyImportExtensions(code, IMPORTER)).toBe(
      `import contactsSdl from '../graphql/contacts.sdl.js'`,
    )
  })

  it('leaves truly static asset imports (.json, .css) alone', () => {
    const jsonImport = `import data from '../data.json'`
    const cssImport = `import styles from '../styles.css'`
    expect(applyImportExtensions(jsonImport, IMPORTER)).toBe(jsonImport)
    expect(applyImportExtensions(cssImport, IMPORTER)).toBe(cssImport)
  })

  it('rewrites explicit .ts extension imports to .js', () => {
    // allowImportingTsExtensions lets users write `./db.ts`, but the
    // compiled file on disk is `db.js`.
    const code = `import { db } from '../lib/db.ts'`
    expect(applyImportExtensions(code, IMPORTER)).toBe(
      `import { db } from '../lib/db.js'`,
    )
  })

  it('rewrites explicit .tsx extension imports to .js', () => {
    const code = `import { Widget } from '../lib/widget.tsx'`
    expect(applyImportExtensions(code, IMPORTER)).toBe(
      `import { Widget } from '../lib/widget.js'`,
    )
  })

  it('rewrites explicit .ts extension on compound-extension SDL imports', () => {
    const code = `import contactsSdl from '../graphql/contacts.sdl.ts'`
    expect(applyImportExtensions(code, IMPORTER)).toBe(
      `import contactsSdl from '../graphql/contacts.sdl.js'`,
    )
  })

  it('rewrites explicit .ts extension in dynamic imports', () => {
    const code = `const mod = await import('../lib/db.ts')`
    expect(applyImportExtensions(code, IMPORTER)).toBe(
      `const mod = await import('../lib/db.js')`,
    )
  })

  it('leaves a .ts import alone when no such source file exists', () => {
    const code = `import { x } from '../lib/nonexistent.ts'`
    expect(applyImportExtensions(code, IMPORTER)).toBe(code)
  })

  it('appends .js to side-effect imports', () => {
    const code = `import '../lib/db'`
    expect(applyImportExtensions(code, IMPORTER)).toBe(`import '../lib/db.js'`)
  })

  it('rewrites explicit .ts extension in side-effect imports', () => {
    const code = `import '../lib/db.ts'`
    expect(applyImportExtensions(code, IMPORTER)).toBe(`import '../lib/db.js'`)
  })

  it('leaves side-effect imports of bare package specifiers untouched', () => {
    const code = `import 'some-package'`
    expect(applyImportExtensions(code, IMPORTER)).toBe(code)
  })

  it('rewrites indented side-effect imports', () => {
    const code = `  import '../lib/db.ts'`
    expect(applyImportExtensions(code, IMPORTER)).toBe(
      `  import '../lib/db.js'`,
    )
  })

  it('rewrites side-effect imports after a semicolon', () => {
    const code = `setup(); import '../lib/db.ts'`
    expect(applyImportExtensions(code, IMPORTER)).toBe(
      `setup(); import '../lib/db.js'`,
    )
  })

  it('leaves side-effect import text inside string data alone', () => {
    const code = `const hint = "add import '../lib/db.ts' to your file"`
    expect(applyImportExtensions(code, IMPORTER)).toBe(code)
  })

  it('rewrites import lines inside multi-line template strings', () => {
    // Documents a known limitation: inside a template literal, a line that
    // starts with a side-effect import is lexically indistinguishable from a
    // real statement, so the statement-position anchor matches it. Avoiding
    // this would require a real parser instead of regex-based rewriting.
    const code = ['const snippet = `', "  import '../lib/db.ts'", '`'].join(
      '\n',
    )
    const expected = ['const snippet = `', "  import '../lib/db.js'", '`'].join(
      '\n',
    )
    expect(applyImportExtensions(code, IMPORTER)).toBe(expected)
  })
})
